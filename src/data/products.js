export const getProductBySlug = (slug) => products.find((p) => p.slug === slug);
export const getProductById = (id) => products.find((p) => p.id === id);
export const getProductsByCategory = (category) => products.filter((p) => p.category?.toLowerCase() === category?.toLowerCase());
export const getFeaturedProducts = () => products.filter((p) => p.isFeatured);
export const getTrendingProducts = () => products.filter((p) => p.isTrending);
export const getOnSaleProducts = () => products.filter((p) => p.isOnSale);
export const getBestSellers = () => products.filter((p) => p.isFeatured).slice(0, 5);
export const getRelatedProducts = (productId, category) => products.filter((p) => p.id !== productId && p.category?.toLowerCase() === category?.toLowerCase()).slice(0, 4);

export const searchProducts = (query) => {
  const q = query.toLowerCase();
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q) ||
      (p.subcategory && p.subcategory.toLowerCase().includes(q)) ||
      p.description.toLowerCase().includes(q)
  );
};

export const formatPrice = (price) => {
  if (price === undefined || price === null || isNaN(price)) return 'PKR 0';
  return `PKR ${Number(price).toLocaleString('en-PK')}`;
};
